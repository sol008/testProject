// 彼岸燈 — design tool build script
// Renders every character sheet of character_options.html to docs/design/options_<char>.png
// (1600 px wide, full page) and regenerates docs/design/CHARACTER_OPTIONS.md from the option data.
//   node tools/design/build_sheets.js            (needs the `playwright` package)
'use strict';
const path = require('path');
const fs = require('fs');
const { chromium } = require('playwright');

const ROOT = path.resolve(__dirname, '..', '..');
const OUT = path.join(ROOT, 'docs', 'design');
const PAGE = 'file://' + path.join(__dirname, 'character_options.html');
const STYLE = {
  classic: '經典仙劍 classic xianxia', donghua: '國漫光影 donghua glow', water: '水彩柔繪 soft watercolour',
  cel: '賽璐璐 sharp cel-shade', ink: '水墨 ink-wash',
};
const EXPR = {
  normal: '平靜', smile: '微笑', laugh: '大笑', sad: '難過', angry: '生氣', surprise: '驚訝', serious: '認真', smug: '得意', shy: '害羞', think: '思考',
};

(async () => {
  fs.mkdirSync(OUT, { recursive: true });
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1600, height: 900 }, deviceScaleFactor: 1 });
  page.on('pageerror', (e) => console.error('page error:', e.message));
  await page.goto(PAGE + '?char=none');
  await page.waitForFunction(() => document.body.dataset.ready);
  const data = await page.evaluate(() => window.DESIGN_OPTIONS.map((c) => ({
    id: c.id, name: c.name, en: c.en, brief: c.brief,
    options: c.options.map((o) => ({ name: o.name, en: o.en, desc: o.desc, gloss: o.gloss || '', style: o.style, expr: o.expr || 'normal' })),
  })));
  for (const ch of data) {
    await page.goto(PAGE + '?char=' + ch.id);
    await page.waitForFunction(() => document.body.dataset.ready);
    await page.waitForTimeout(200);
    const file = path.join(OUT, `options_${ch.id}.png`);
    await page.screenshot({ path: file, fullPage: true });
    console.log('wrote', path.relative(ROOT, file));
  }
  await browser.close();

  // ---------------------------------------------------------------- markdown
  const L = [];
  L.push('# 《彼岸燈》主要角色造型提案 — Character Design Options', '');
  L.push('> 給選角用的造型方案總表：五位主角（沈星河、白芷、洛紅纓、雲歸、糰子）各 10 款，彼此在**髮型／剪影、配色、服裝剪裁與層次、配件、年齡感與表情、畫風**上都刻意拉開差距；每位角色的第 1 款是忠於 Story Bible 的「原設定」，其餘為延伸與大膽詮釋。');
  L.push('> *A pick-list of 10 look options for each of the five leads. Option 1 is always the bible-faithful "canon" look; the rest are variations and a few bolder reinterpretations.*', '');
  L.push('## 怎麼看 / How to view', '');
  L.push('- 圖檔：`docs/design/options_<角色>.png`（每張一位角色，1600 px 寬）。每張卡片 = 編號、方案名、畫風標籤、一行說明；卡片下方另有**地圖比例 Q 版＋純黑剪影**，用來檢查角色在遊戲地圖上是否一眼可辨。');
  L.push('- 互動版：用瀏覽器開 `tools/design/character_options.html`（加 `?char=xinghe|baizhi|hongying|yungui|tuanzi` 只看單一角色；滑鼠停在卡片上會顯示英文說明）。重新產生圖檔與本文件：`node tools/design/build_sheets.js`。');
  L.push('- 方案可以**混搭**：例如「A 方案的髮型 + B 方案的配色」，或把造型與畫風分開挑（畫風標籤代表的是整體美術方向，不綁定造型）。');
  L.push('- *Images are in `docs/design/`; the live page is `tools/design/character_options.html`. Options can be mixed and matched (hair from one, palette from another); the art-direction tag is independent of the costume design.*', '');
  L.push('**畫風標籤 Art-direction tags**：' + Object.values(STYLE).map((s) => '`' + s + '`').join('、'), '');
  for (const ch of data) {
    L.push(`## ${ch.name} — ${ch.en}`, '');
    L.push(ch.brief, '');
    L.push(`![${ch.name} options](options_${ch.id}.png)`, '');
    L.push('| # | 方案 Option | 畫風 / 表情 | 說明（English gloss） |');
    L.push('|---|---|---|---|');
    ch.options.forEach((o, i) => {
      const n = String(i + 1).padStart(2, '0');
      L.push(`| ${n} | **${o.name}**<br>*${o.en}* | ${STYLE[o.style] || o.style}<br>${EXPR[o.expr] || o.expr} | ${o.desc}<br>*${o.gloss}* |`);
    });
    L.push('');
  }
  L.push('---', '', '*Generated by `tools/design/build_sheets.js` from the option data in `tools/design/options*.js` and `tools/design/tuanzi.js`.*', '');
  fs.writeFileSync(path.join(OUT, 'CHARACTER_OPTIONS.md'), L.join('\n'));
  console.log('wrote docs/design/CHARACTER_OPTIONS.md');
})().catch((e) => { console.error(e); process.exit(1); });
