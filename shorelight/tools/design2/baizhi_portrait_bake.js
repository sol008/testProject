// Bake 白芷's in-game portraits → js/gfx/portraits_baizhi.js (webp data URLs, used by G.Portraits for 'baizhi').
//   node tools/design2/baizhi_portrait_bake.js            (all)      |  ... preview  (contact sheet to stdout path)
const path = require('path'), fs = require('fs');
const { chromium } = require('playwright');
const ROOT = path.resolve(__dirname, '..', '..');
const PAGE = 'file://' + path.join(__dirname, 'baizhi_portrait.html');
const EXPRS = ['normal', 'smile', 'laugh', 'sad', 'cry', 'angry', 'surprise', 'think', 'shy', 'hurt', 'serious', 'smug'];
const NOBLINK = new Set(['laugh', 'hurt']);
(async () => {
  const b = await chromium.launch();
  const out = {};
  for (const e of EXPRS) for (const bl of NOBLINK.has(e) ? [0] : [0, 1]) {
    const p = await b.newPage({ viewport: { width: 600, height: 680 } });
    await p.goto(`${PAGE}?expr=${e}&blink=${bl}&k=2`);
    await p.waitForFunction(() => document.body.dataset.ready);
    const err = await p.evaluate(() => document.body.dataset.error);
    if (err) { console.error(e, err); process.exit(1); }
    out[e + (bl ? '_blink' : '')] = await p.evaluate(() => document.getElementById('cv').toDataURL('image/webp', 0.9));
    await p.close();
    process.stdout.write('.');
  }
  await b.close();
  let js = '// AUTO-GENERATED by tools/design2/baizhi_portrait_bake.js — do not edit by hand.\n';
  js += '// 白芷 dialogue portraits (client pick v2 #02 藍衫笛歌), baked from the design-sheet drawing at 600x680 (2x of 300x340).\n';
  js += "'use strict';\nG.PortraitImages = G.PortraitImages || {};\nG.PortraitImages.baizhi = " + JSON.stringify(out, null, 0).replace(/","/g, '",\n"') + ';\n';
  fs.writeFileSync(path.join(ROOT, 'js/gfx/portraits_baizhi.js'), js);
  console.log('\nwrote js/gfx/portraits_baizhi.js', Math.round(js.length / 1024) + ' KB');
})();
